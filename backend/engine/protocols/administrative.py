def parse_topic_boundaries(
    raw: str, transcript_len: int,
) -> list[dict[str, Any]]:
    """Parse the topic-detection response into validated ranges.

    Drops topics with out-of-range or inverted indices. Clamps to
    the transcript length. Returns a list of {name, start_idx,
    end_idx} dicts; empty list on parse failure (caller should fall
    back to the flat single-topic path).
    """
    obj = _extract_json(raw)
    if not obj:
        return []
    raw_topics = obj.get("topics") if isinstance(obj, dict) else None
    if not isinstance(raw_topics, list):
        return []

    cleaned: list[dict[str, Any]] = []
    for t in raw_topics:
        if not isinstance(t, dict):
            continue
        name = str(t.get("name", "")).strip()
        try:
            start = int(t.get("start_idx", -1))
            end = int(t.get("end_idx", -1))
        except (TypeError, ValueError):
            continue
        if not name or start < 0 or end < start:
            continue
        # Clamp to transcript length so a hallucinated index doesn't
        # crash the slicer.
        start = min(start, transcript_len - 1)
        end = min(end, transcript_len - 1)
        if start <= end:
            cleaned.append({"name": name, "start_idx": start, "end_idx": end})
    return cleaned


