_CONTEXT_ATTENDEES_RE = re.compile(
    r"Участники\s+совещания\s*:\s*([^\n\r.]+)",
    re.IGNORECASE,
)


def _participants_from_context(meeting_context: Optional[str]) -> list[str]:
    """Extract participant names from operator-provided context.

    Looks for the marker 'Участники совещания: X, Y, Z' which is emitted
    by the frontend UploadPage when the user checks attendee boxes. Names
    are split by comma/semicolon and trimmed. Used as a fallback when the
    LLM's participants field is empty — the operator's list is
    authoritative because it's from a curated checklist, not inferred.
    """
    if not meeting_context:
        return []
    match = _CONTEXT_ATTENDEES_RE.search(meeting_context)
    if not match:
        return []
    raw = match.group(1)
    names = [n.strip() for n in re.split(r"[,;]+", raw)]
    return [n for n in names if n]


def _clean_str(value: Any) -> str:
    """Treat 'нет' / 'none' / 'null' / 'n/a' / '-' as empty.

    The flat-schema prompt requires the LLM to use \"нет\" as the
    canonical empty value, so the parser maps those back to empty
    strings before they reach the formatter.
    """
    text = str(value or "").strip()
    if text.lower() in ("нет", "none", "null", "n/a", "-"):
        return ""
    return text


def _absorb_flat_items(
    raw_items: Any,
    speaker_field: str = "speaker",
    has_owner: bool = False,
    has_deadline: bool = False,
    kind: str = "thesis",
) -> list[FlatProtocolItem]:
    """Convert an LLM-emitted JSON list of dicts into FlatProtocolItem
    instances. Filters out entries with empty text. Tolerates partial
    fields per the schema (decisions/open_questions/risks need speaker,
    tasks need owner instead).
    """
    out: list[FlatProtocolItem] = []
    if not isinstance(raw_items, list):
        return out
    for entry in raw_items:
        if not isinstance(entry, dict):
            continue
        text = _clean_str(entry.get("text"))
        if not text:
            continue
        speaker = _clean_str(entry.get(speaker_field, "")) if speaker_field else ""
        evidence = _clean_str(entry.get("evidence"))
        owner = None
        if has_owner:
            owner_clean = _clean_str(entry.get("owner"))
            owner = owner_clean if owner_clean else None
        deadline = None
        if has_deadline:
            deadline_clean = _clean_str(entry.get("deadline"))
            deadline = deadline_clean if deadline_clean else None
        # Confidence label (task #45). Tolerant parser — anything not
        # in the {high, medium, low} set defaults to "medium" so a
        # malformed LLM output still produces a renderable protocol.
        confidence_raw = (
            _clean_str(entry.get("confidence", "")).lower()
        )
        if confidence_raw in ("high", "medium", "low"):
            confidence = confidence_raw  # type: ignore[assignment]
        else:
            confidence = "medium"
        out.append(
            FlatProtocolItem(
                kind=kind,
                text=text,
                speaker=speaker,
                evidence=evidence,
                owner=owner,
                deadline=deadline,
                confidence=confidence,
            )
        )
    return out


def _normalise_item_kind(value: Any) -> str:
    """Return a supported practical item kind."""
    raw = str(value or "").strip().lower()
    aliases = {
        "decision": "decision",
        "decisions": "decision",
        "task": "task",
        "action": "task",
        "action_item": "task",
        "open_question": "open_question",
        "question": "open_question",
        "risk": "risk",
        "blocker": "risk",
        "thesis": "thesis",
        "takeaway": "thesis",
        "agreement": "decision",
    }
    return aliases.get(raw, "thesis")


def _absorb_practical_items(raw_items: Any) -> list[FlatProtocolItem]:
    """Convert practical v1.0 JSON items into FlatProtocolItem."""
    out: list[FlatProtocolItem] = []
    if not isinstance(raw_items, list):
        return out
    for entry in raw_items:
        if not isinstance(entry, dict):
            continue
        text = _clean_str(entry.get("text"))
        if not text:
            continue
        confidence_raw = _clean_str(entry.get("confidence", "")).lower()
        confidence = (
            confidence_raw
            if confidence_raw in ("high", "medium", "low")
            else "medium"
        )
        owner = _clean_str(entry.get("owner"))
        deadline = _clean_str(entry.get("deadline"))
        out.append(
            FlatProtocolItem(
                kind=_normalise_item_kind(
                    entry.get("type", entry.get("kind", "thesis"))
                ),
                text=text,
                speaker=_clean_str(entry.get("speaker")),
                evidence=_clean_str(
                    entry.get("evidence_quote", entry.get("evidence"))
                ),
                timestamp=_clean_str(entry.get("timestamp")),
                owner=owner or None,
                deadline=deadline or None,
                confidence=confidence,  # type: ignore[arg-type]
            )
        )
    return out


def parse_practical_items(raw_text: str) -> list[FlatProtocolItem]:
    """Parse an items-only practical recall response."""
    parsed = _extract_json(raw_text)
    if not parsed:
        return []
    return _absorb_practical_items(parsed.get("items"))


def parse_response(
    raw_text: str,
    aligned: Optional[list] = None,
    meeting_context: Optional[str] = None,
) -> ProtocolResult:
    """Parse the flat 9-section LLM JSON into an AdministrativeProtocol.

    The LLM emits 9 top-level keys per the prompt schema; each item
    list is converted to FlatProtocolItem with text/speaker/evidence
    plus task-only owner/deadline. Empty values default to empty
    strings or None per the model.

    The aligned transcript populates the stenogram `turns` field
    (verbatim ground truth, not LLM-generated). meeting_context is
    scanned for the operator's attendee list as a fallback when the
    LLM returns empty participants.

    Args:
        raw_text: Raw LLM output (JSON).
        aligned: List of AlignedSegment for stenogram turns.
        meeting_context: User-provided context string. Scanned for
            'Участники совещания: ...' fallback.

    Returns:
        ProtocolResult with AdministrativeProtocol payload.
    """
    parsed = _extract_json(raw_text) or {}

    meeting_date = _clean_str(parsed.get("meeting_date"))
    meeting_goal = _clean_str(parsed.get("meeting_goal"))
    summary = _clean_str(parsed.get("summary"))

    participants_raw = parsed.get("participants") or []
    participants: list[str] = []
    if isinstance(participants_raw, list):
        for entry in participants_raw:
            cleaned = _clean_str(entry)
            if cleaned:
                participants.append(cleaned)

    # Fallback: if the LLM returned empty participants but the
    # operator's context has a 'Участники совещания: X, Y, Z' list,
    # use that list. The operator picked these names from a checklist
    # so they are authoritative — no need to verify against transcript.
    if not participants:
        fallback = _participants_from_context(meeting_context)
        if fallback:
            logger.info(
                "LLM returned empty participants; using %d operator-provided "
                "names from context", len(fallback),
            )
            participants = fallback

    topics_raw = parsed.get("topics") or []
    topics: list[str] = []
    if isinstance(topics_raw, list):
        for entry in topics_raw:
            cleaned = _clean_str(entry)
            if cleaned:
                topics.append(cleaned)

    # Practical v1.0 schema: one unified items list. Older/legacy
    # LLM output may still contain flat buckets; those are absorbed
    # below and merged into items for the new formatter.
    items = _absorb_practical_items(parsed.get("items"))

    # Decisions, open_questions, risks each take {text, speaker, evidence}.
    # Tasks take {text, owner, deadline, evidence} (no speaker — owner
    # is the meaningful field for who's responsible).
    decisions = _absorb_flat_items(parsed.get("decisions"), kind="decision")
    tasks = _absorb_flat_items(
        parsed.get("tasks"),
        speaker_field="",  # tasks don't carry speaker; owner is what matters
        has_owner=True,
        has_deadline=True,
        kind="task",
    )
    open_questions = _absorb_flat_items(
        parsed.get("open_questions"), kind="open_question"
    )
    risks = _absorb_flat_items(parsed.get("risks"), kind="risk")

    if items:
        # Keep old buckets populated for API/UI compatibility.
        decisions = [item for item in items if item.kind == "decision"]
        tasks = [item for item in items if item.kind == "task"]
        open_questions = [
            item for item in items if item.kind == "open_question"
        ]
        risks = [item for item in items if item.kind == "risk"]
    else:
        items = [
            *decisions,
            *tasks,
            *open_questions,
            *risks,
        ]

    # Build stenogram turns from the aligned transcript. Not sourced
    # from the LLM — this is verbatim ground truth, one turn per
    # aligned segment. start_s is captured for [HH:MM:SS] DOCX render.
    turns: list[CourtHearingTurn] = []
    if aligned:
        for seg in aligned:
            text = (getattr(seg, "text", "") or "").strip()
            if not text:
                continue
            label = (
                getattr(seg, "speaker_name", None)
                or getattr(seg, "speaker_id", None)
                or "Говорящий"
            )
            start_s = getattr(seg, "start", None)
            try:
                start_s = float(start_s) if start_s is not None else None
            except (TypeError, ValueError):
                start_s = None
            turns.append(
                CourtHearingTurn(
                    speaker=str(label).strip(),
                    text=text,
                    start_s=start_s,
                )
            )

    payload = AdministrativeProtocol(
        title="Протокол административного совещания",
        meeting_date=meeting_date,
        meeting_goal=meeting_goal,
        summary=summary,
        participants=participants,
        topics=topics,
        items=items,
        decisions=decisions,
        tasks=tasks,
        open_questions=open_questions,
        risks=risks,
        # Legacy department field stays empty for new flat-schema runs.
        # Formatter detects this and uses the new flat renderer.
        departments=[],
        turns=turns,
    )
    return ProtocolResult(meeting_type="administrative", payload=payload)


# =====================================================================
# Shared JSON extractor
# =====================================================================

def _extract_json(raw: str) -> Optional[dict[str, Any]]:
    """Extract the first top-level JSON object from raw LLM output."""
    if not raw:
        return None
    text = raw.strip()
    text = re.sub(r"^```(?:json)?\s*", "", text)
    text = re.sub(r"\s*```\s*$", "", text)
    try:
        result = json.loads(text)
        if isinstance(result, dict):
            return result
    except json.JSONDecodeError:
        pass
    match = re.search(r"\{[\s\S]*\}", text)
    if match:
        try:
            result = json.loads(match.group(0))
            if isinstance(result, dict):
                return result
        except json.JSONDecodeError as exc:
            logger.warning("Failed to parse fallback JSON block: %s", exc)
    logger.warning("Administrative LLM output was not valid JSON; returning empty")
    return None


# =====================================================================
# Map-reduce topic-segmented protocol (Sprint 2026-04-30, task #35)
# =====================================================================
#
# Two-step LLM process replacing the single-call flat 9-section path
# for administrative meetings:
#
#   Step 1 (boundary detection): one Gemma call asking "split the
#     transcript into thematic segments". Returns JSON of {name,
#     start_idx, end_idx} ranges.
#
#   Step 2 (per-topic summary): for each topic range, one Gemma call
#     asking for {discussion, decisions, tasks, open_questions}
#     scoped to that topic only. Smaller prompts → better attention,
#     more items extracted, more topic-relevant grounding.
#
# Risks remain at the protocol level (cross-cutting). Stenogram comes
# from the aligned transcript, not from the LLM. Topic_summaries
# populates the new field; flat decisions/tasks/questions are also
# populated as the union of per-topic items so the existing flat
# renderer has data when topic-segmented rendering is disabled or the
# JSON parse fails.
#
# Speed cost: 1 + N Gemma calls vs 2 (extract + verify) in the flat
# path. On a 50-min meeting with ~8 topics and 60s/call this is
# roughly +6 min — acceptable for a quality jump on the protocol the
# user actually keeps.

# Number transcript segments and emit "[idx] Speaker: text" lines so
# the LLM can return integer indices unambiguously. The boundary call
# uses these indices; the per-topic call slices the same transcript.
def _format_indexed_transcript(aligned: list[Any]) -> tuple[str, list[Any]]:
    """Return (LLM-friendly text, ordered seg list).

    Filters out empty segments so the indices the LLM receives match
    the indices we'll slice with later. Returns the ordered list so
    callers don't have to re-filter.
    """
    rows: list[str] = []
    kept: list[Any] = []
    for seg in aligned or []:
        text = (getattr(seg, "text", "") or "").strip()
        if not text:
            continue
        speaker = (
            getattr(seg, "speaker_name", None)
            or getattr(seg, "speaker_id", None)
            or "Говорящий"
        )
        idx = len(kept)
        rows.append(f"[{idx}] {speaker}: {text}")
        kept.append(seg)
    return "\n".join(rows), kept


