def parse_topic_summary(raw: str, topic_name: str) -> TopicSummary:
    """Parse a single per-topic LLM response into a TopicSummary.

    On parse failure returns an empty TopicSummary with just the
    name set — the topic still appears in the protocol so the reader
    can audit the segmentation, but with no synthesised content.
    """
    obj = _extract_json(raw)
    if not obj:
        return TopicSummary(name=topic_name)

    discussion = str(obj.get("discussion", "")).strip()

    def _items(key: str, *, has_owner: bool, has_deadline: bool) -> list[FlatProtocolItem]:
        out: list[FlatProtocolItem] = []
        raw_items = obj.get(key)
        if not isinstance(raw_items, list):
            return out
        for it in raw_items:
            if not isinstance(it, dict):
                continue
            text = str(it.get("text", "")).strip()
            if not text:
                continue
            evidence = str(it.get("evidence", "")).strip()
            # Drop items without evidence — anti-hallucination policy
            # mirrors the flat-format verifier.
            if not evidence:
                continue
            speaker = str(it.get("speaker", "")).strip()
            owner = (
                str(it.get("owner", "")).strip()
                if has_owner else ""
            ) or None
            deadline_raw = it.get("deadline") if has_deadline else None
            deadline = (
                str(deadline_raw).strip()
                if isinstance(deadline_raw, str) and deadline_raw.strip()
                and deadline_raw.strip().lower() not in ("null", "none", "нет")
                else None
            )
            out.append(
                FlatProtocolItem(
                    text=text,
                    speaker=speaker,
                    evidence=evidence,
                    owner=owner,
                    deadline=deadline,
                )
            )
        return out

    return TopicSummary(
        name=topic_name,
        discussion=discussion,
        decisions=_items("decisions", has_owner=False, has_deadline=False),
        tasks=_items("tasks", has_owner=True, has_deadline=True),
        open_questions=_items(
            "open_questions", has_owner=False, has_deadline=False
        ),
    )


def assemble_topic_segmented_protocol(
    *,
    aligned: list[Any],
    meeting_date: str,
    meeting_goal: str,
    summary: str,
    participants: list[str],
    risks: list[FlatProtocolItem],
    topic_summaries: list[TopicSummary],
    meeting_context: str = "",
) -> ProtocolResult:
    """Build the final ProtocolResult for a topic-segmented admin meeting.

    Combines (a) the topic-segmented bodies into ``topic_summaries``,
    (b) flat decisions/tasks/open_questions as the UNION across topics
    so the legacy renderer still works as a fallback, (c) topic
    *names* into the legacy ``topics`` list, (d) verbatim stenogram
    turns from the aligned transcript.

    The formatter dispatches: when ``topic_summaries`` is non-empty
    it renders the topic-grouped layout; otherwise it falls back to
    the flat 9-section layout.
    """
    # Flatten per-topic items into the legacy unified lists. This
    # keeps backward-compat: an older formatter / frontend / external
    # consumer that doesn't know about topic_summaries still gets
    # readable decisions / tasks / questions.
    flat_decisions: list[FlatProtocolItem] = []
    flat_tasks: list[FlatProtocolItem] = []
    flat_questions: list[FlatProtocolItem] = []
    for t in topic_summaries:
        flat_decisions.extend(t.decisions)
        flat_tasks.extend(t.tasks)
        flat_questions.extend(t.open_questions)

    topic_names = [t.name for t in topic_summaries if t.name.strip()]

    turns: list[CourtHearingTurn] = []
    for seg in aligned or []:
        text = (getattr(seg, "text", "") or "").strip()
        if not text:
            continue
        label = (
            getattr(seg, "speaker_name", None)
            or getattr(seg, "speaker_id", None)
            or "Говорящий"
        )
        start_s = getattr(seg, "start", None)
        try:
            start_s = float(start_s) if start_s is not None else None
        except (TypeError, ValueError):
            start_s = None
        turns.append(
            CourtHearingTurn(
                speaker=str(label).strip(),
                text=text,
                start_s=start_s,
            )
        )

    payload = AdministrativeProtocol(
        title="Протокол административного совещания",
        meeting_date=meeting_date,
        meeting_goal=meeting_goal,
        summary=summary,
        participants=participants,
        topics=topic_names,
        decisions=flat_decisions,
        tasks=flat_tasks,
        open_questions=flat_questions,
        risks=risks,
        topic_summaries=topic_summaries,
        departments=[],
        turns=turns,
    )
    return ProtocolResult(meeting_type="administrative", payload=payload)


