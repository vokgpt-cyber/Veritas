"""Administrative meeting protocol builder.

Flat 9-section format (T3.3, 2026-04-23) matching EPAM IT's
production prompt schema. Sections in DOCX render order:
    1. Title + meeting date
    2. Participants
    3. Meeting goal (if stated)
    4. Brief summary (3-7 sentences)
    5. Topics (bullets, neutral phrasing)
    6. Decisions (with speaker + evidence)
    7. Tasks (with owner + optional deadline + evidence)
    8. Open questions (with speaker + evidence)
    9. Risks (with speaker + evidence) — separate from open questions
   10. Stenogram (verbatim aligned-transcript turns)

LLM emits flat lists; parser does no department canonicalisation
beyond cleaning empty values. This replaces the earlier department-
grouped layout (HR/Finance/IT/...). Legacy department fields are still
recognised by the formatter for protocols generated by older runs
(see formatter._format_administrative_docx).
"""
