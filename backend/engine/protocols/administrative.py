def build_prompt(
    transcript_text: str,
    language: str = "ru",
    meeting_context: str = "",
) -> list[dict]:
    """Build the Ollama chat prompt for an administrative meeting.

    Flat 9-section schema (T3.3, 2026-04-23) matching the EPAM IT
    team's production prompt verbatim, with two extensions:
      * `meeting_date` field at top (we already populate this).
      * `evidence` carried per-item (the IT prompt also requires this).

    Risks are kept as a separate top-level key (per IT and per
    user 2026-04-23 decision) — they answer "what's blocking us"
    while open_questions answers "what's unanswered". Different
    semantics, different sections.

    Args:
        transcript_text: Formatted transcript.
        language: "ru" or "en" — admin meetings are ru-only in practice.
        meeting_context: User-provided context.
    """
    return _build_practical_prompt(transcript_text, meeting_context)

    # 2026-05-04 prompt rewrite (task #44). Replaces the heavy
    # "ты секретарь, не выдумывай, лучше вернуть меньше" prompt with
    # an industry-pattern direct prompt modeled on Anthropic Meeting
    # Scribe + Notion AI Meeting Notes + OpenAI Cookbook guidance.
    #
    # Why we rewrote: the previous prompt had three layers of defense
    # (defensive persona + strict evidence requirement + verification
    # pass that deletes) that combined multiplicatively — producing
    # protocols with 2-3 decisions on hour-long meetings that had 15.
    # User feedback (2026-05-04): IT team's protocol with same Gemma 4
    # 26B model but simpler prompt produces noticeably more useful
    # output. Confirmed by 2025-2026 industry research: every leading
    # meeting AI (Otter, Fireflies, Notion, Teams, Anthropic Scribe)
    # uses direct task instruction without defensive persona framing.
    #
    # Key differences from the old prompt:
    # 1. No "ты секретарь" persona — direct task instruction.
    # 2. Implicit decisions ARE decisions: "давайте перенесём",
    #    "ну хорошо, делаем так" count. Previous prompt explicitly
    #    excluded these, which lost most real-world decisions.
    # 3. Owner/deadline are nice-to-have, not required. User said
    #    2026-05-04: "людей и сроки мы найдём потом как проставить".
    # 4. Evidence remains in schema but is descriptive (transcript
    #    quote helping the user verify), not gatekeeping. The
    #    verification pass (task #45) uses it to MARK confidence,
    #    not to delete items.
    # 5. Few-shot examples for decision/task/open_question give the
    #    model concrete grounding (research: few-shot is the single
    #    highest-leverage prompt change for extraction tasks).
    system = (
        "Извлеки структурированный протокол из стенограммы "
        "административного совещания. Твоя цель — помочь коллеге, "
        "который не присутствовал на встрече, понять её итоги.\n"
        "\n"
        "Извлекай ВСЁ существенное: явные и неявные решения, поручения "
        "и договорённости, открытые вопросы, риски и блокеры.\n"
        "Лучше включить сомнительный пункт с пометкой опорной цитаты — "
        "пользователь проверит и удалит ненужное вручную.\n"
        "\n"
        "ФОРМАТ ОТВЕТА — JSON со следующей плоской схемой (9 ключей "
        "верхнего уровня, без вложенных группировок):\n"
        "{\n"
        '  "meeting_date": "ДД.ММ.ГГГГ или \\"нет\\" если в стенограмме отсутствует",\n'
        '  "meeting_goal": "цель встречи, если явно или ясно сформулирована, иначе \\"нет\\"",\n'
        '  "summary": "3-7 предложений связного краткого содержания: какие темы обсуждались, какие итоги",\n'
        '  "participants": ["имя или роль участника", ...],\n'
        '  "topics": ["короткая нейтральная формулировка темы", ...],\n'
        '  "decisions": [\n'
        '    {"text": "суть решения", "speaker": "кто принял или предложил, иначе пусто", "evidence": "короткая цитата из стенограммы", "confidence": "high|medium|low"}\n'
        '  ],\n'
        '  "tasks": [\n'
        '    {"text": "описание поручения или договорённости", "owner": "кому, иначе пусто", "deadline": "срок, иначе пусто", "evidence": "короткая цитата", "confidence": "high|medium|low"}\n'
        '  ],\n'
        '  "open_questions": [\n'
        '    {"text": "формулировка нерешённого вопроса", "speaker": "кто поднял, иначе пусто", "evidence": "короткая цитата", "confidence": "high|medium|low"}\n'
        '  ],\n'
        '  "risks": [\n'
        '    {"text": "проблема, блокер или негативный сценарий", "speaker": "кто озвучил, иначе пусто", "evidence": "короткая цитата", "confidence": "high|medium|low"}\n'
        '  ]\n'
        "}\n"
        "\n"
        "CONFIDENCE — оценивай каждый decision/task/open_question/risk:\n"
        "• high — явное и однозначное: есть прямой маркер «решили», "
        "«договорились», «утверждаем»; либо очевидное согласие на "
        "конкретное предложение; либо явно поставленная задача с "
        "исполнителем\n"
        "• medium — ясно из контекста, но без явного маркера: "
        "«давайте сделаем так», «ну окей»; либо задача без явного "
        "исполнителя; либо открытый вопрос; либо озвученный риск\n"
        "• low — выведено из обсуждения, неоднозначно, опорная цитата "
        "слабая\n"
        "Используй low щедро — пользователь увидит low-элементы с "
        "пометкой и решит, оставить или удалить.\n"
        "\n"
        "ЧТО СЧИТАТЬ РЕШЕНИЕМ (важно — мы хотим зафиксировать решения, "
        "а не упустить их):\n"
        "Решение — это любая зафиксированная договорённость о действии "
        "или изменении статуса. Сюда входят:\n"
        "• Явные маркеры: «решили», «договорились», «принято», «утверждаем»\n"
        "• Согласие на предложение: «давайте перенесём» — решение перенести; "
        "«ну окей, делаем так» — решение сделать; «согласен» в ответ "
        "на предложение — решение принять предложение\n"
        "• Отказ или отсрочка: «пока не делаем», «отложили», «не будем» — "
        "это тоже решение\n"
        "• Делегирование: «пусть Иванов возьмёт» — решение поручить Иванову\n"
        "Не решение: размышления вслух, риторические вопросы, гипотезы, "
        "обсуждение вариантов без явного выбора.\n"
        "\n"
        "ЧТО СЧИТАТЬ ПОРУЧЕНИЕМ:\n"
        "Поручение — это конкретное действие, которое кто-то взял или "
        "получил на исполнение. Если исполнитель не назван, всё равно "
        "включи поручение и оставь owner пустым — пользователь "
        "проставит вручную. Если срок не назван — оставь deadline "
        "пустым.\n"
        "\n"
        "ЧТО СЧИТАТЬ ОТКРЫТЫМ ВОПРОСОМ:\n"
        "То, что обсуждали, но не закрыли в этой встрече: «нужно подумать», "
        "«вернёмся к этому», «непонятно как сделать», заданный вопрос "
        "без ответа.\n"
        "\n"
        "ЧТО СЧИТАТЬ РИСКОМ:\n"
        "Угроза, блокер или возможный негативный сценарий, явно "
        "озвученный участником. Например: «если не успеем — клиент уйдёт», "
        "«это может выйти за бюджет», «зависит от внешнего фактора».\n"
        "\n"
        "EVIDENCE:\n"
        "Для каждого decision/task/open_question/risk приведи в поле "
        "evidence короткую цитату из стенограммы (5-15 слов) — это "
        "помогает пользователю быстро найти источник в записи.\n"
        "Если короткой однозначной цитаты нет, всё равно включи "
        "элемент — приведи самую близкую фразу или короткий пересказ.\n"
        "\n"
        "PARTICIPANTS:\n"
        "Если оператор явно перечислил участников в КОНТЕКСТЕ ВСТРЕЧИ "
        "ниже (строка «Участники совещания: …»), используй именно этот "
        "список как источник имён без проверки.\n"
        "\n"
        "ЯЗЫК:\n"
        "Все поля — только на русском. Имена собственные, бренды, "
        "технические термины оставляй в оригинале.\n"
        "\n"
        "ВЫВОД:\n"
        "Ответь ТОЛЬКО JSON-объектом. Никаких markdown-блоков, никаких "
        "комментариев. Точно эти 9 ключей верхнего уровня."
    )

    if meeting_context:
        system += (
            "\n\nКОНТЕКСТ ВСТРЕЧИ (добавочная информация от оператора, "
            "используй только если согласуется со стенограммой):\n"
            f"{meeting_context}"
        )

    user = (
        "Стенограмма административного совещания:\n\n"
        f"{transcript_text}"
    )

    return [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]


def _build_practical_prompt(
    transcript_text: str,
    meeting_context: str = "",
) -> list[dict]:
    """Build the v1.0 practical admin protocol prompt.

    The product direction is "less report about the meeting, more what
    to remember and do". The DOCX should become a useful work product:
    participants plus a single list of practical takeaways backed by
    short transcript evidence.
    """
    system = (
        "Extract a practical administrative meeting protocol from the "
        "transcript. The goal is NOT to write a report about the meeting. "
        "The goal is to help a colleague quickly understand what must be "
        "remembered, checked, decided, or done.\n\n"
        "Output only JSON with this shape:\n"
        "{\n"
        '  "meeting_date": "DD.MM.YYYY or empty",\n'
        '  "participants": ["names from the operator context, if provided"],\n'
        '  "items": [\n'
        "    {\n"
        '      "type": "decision|task|open_question|risk|thesis",\n'
        '      "text": "short practical takeaway in Russian",\n'
        '      "owner": "responsible person/department, or empty",\n'
        '      "deadline": "deadline, or empty",\n'
        '      "speaker": "who proposed/confirmed/raised it, or empty",\n'
        '      "evidence_quote": "5-20 words from the transcript",\n'
        '      "timestamp": "HH:MM:SS or MM:SS if visible, or empty",\n'
        '      "confidence": "high|medium|low"\n'
        "    }\n"
        "  ]\n"
        "}\n\n"
        "What to include in items:\n"
        "- explicit and implicit decisions;\n"
        "- tasks and assignments, even if owner/deadline are missing;\n"
        "- important agreements and management theses;\n"
        "- open questions that must not be lost;\n"
        "- risks, blockers, or problems that require attention.\n\n"
        "Task owner inference:\n"
        "- If the owner is explicitly named, use that person or department.\n"
        "- If the owner is not named but the discussion is clearly about a "
        "department, function, or participant role from the operator context, "
        "fill owner with that department/person and set confidence to medium "
        "or low.\n"
        "- If the speaker says a task in a generic way (for example, "
        "\"need to prepare\", \"let's check\", \"we should send\"), infer the "
        "owner from the current discussed unit: HR tasks -> HR, IT tasks -> IT, "
        "finance tasks -> Finance, litigation/admin/document tasks -> the "
        "relevant department/person from context.\n"
        "- If there is no reliable context, leave owner empty.\n\n"
        "Deadline inference:\n"
        "- If a deadline is explicitly stated, use it.\n"
        "- If no deadline is stated but this is an ordinary operational task, "
        "use \"1-2 недели\" and set confidence to medium or low.\n"
        "- If the task is urgent or phrased as immediate, use \"1 неделя\".\n"
        "- If the task is complex, requires approvals, several teams, or "
        "document drafting/coordination, use \"до 1 месяца\".\n"
        "- If even this is too uncertain, leave deadline empty.\n\n"
        "Coverage rule:\n"
        "- Do not return a top-10 summary. Scan the transcript "
        "chronologically from beginning to end.\n"
        "- For long administrative meetings, a useful protocol often has "
        "15-35 items per hour. A 90-120 minute meeting may legitimately "
        "contain 25-60 items.\n"
        "- Include narrow local points if they may later become document "
        "drafting material. The user will remove excess items manually.\n"
        "- Do not merge separate decisions just because they belong to the "
        "same broad topic.\n\n"
        "Do not create separate sections for goal, summary, topics, risks, "
        "questions, or transcript. Everything useful goes into items.\n"
        "Prefer completeness over excessive caution. If a point is useful "
        "but not fully certain, include it with confidence=low.\n"
        "Do not invent facts. Each item must have a short evidence_quote "
        "from the transcript or the closest short paraphrase if the ASR text "
        "is too noisy.\n"
        "Write all user-facing fields in Russian. Keep names, brands, and "
        "technical terms as spoken.\n"
    )
    if meeting_context:
        system += (
            "\nOperator-provided context. Treat the participant list here "
            "as authoritative if present:\n"
            f"{meeting_context}\n"
        )
    user = (
        "Administrative meeting transcript:\n\n"
        f"{transcript_text}"
    )
    return [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]


def _practical_response_format_schema() -> dict[str, Any]:
    """Ollama structured-output schema for the practical admin layout."""
    confidence = {"type": "string", "enum": ["high", "medium", "low"]}
    item_type = {
        "type": "string",
        "enum": ["decision", "task", "open_question", "risk", "thesis"],
    }
    practical_item = {
        "type": "object",
        "additionalProperties": False,
        "properties": {
            "type": item_type,
            "text": {"type": "string"},
            "owner": {"type": "string"},
            "deadline": {"type": "string"},
            "speaker": {"type": "string"},
            "evidence_quote": {"type": "string"},
            "timestamp": {"type": "string"},
            "confidence": confidence,
        },
        "required": [
            "type",
            "text",
            "owner",
            "deadline",
            "speaker",
            "evidence_quote",
            "timestamp",
            "confidence",
        ],
    }
    return {
        "type": "object",
        "additionalProperties": False,
        "properties": {
            "meeting_date": {"type": "string"},
            "participants": {"type": "array", "items": {"type": "string"}},
            "items": {"type": "array", "items": practical_item},
        },
        "required": ["meeting_date", "participants", "items"],
    }


def practical_items_response_format_schema() -> dict[str, Any]:
    """Structured-output schema for an items-only recall pass."""
    base = _practical_response_format_schema()
    return {
        "type": "object",
        "additionalProperties": False,
        "properties": {
            "items": base["properties"]["items"],
        },
        "required": ["items"],
    }


def build_practical_recall_prompt(
    *,
    window_transcript: str,
    existing_items: list[str],
    meeting_context: str = "",
    window_label: str = "",
) -> list[dict]:
    """Build a focused recall prompt for one chronological window.

    The primary full-transcript call is good at finding the largest
    takeaways, but long admin meetings often need a second pass over
    smaller windows so local decisions and tasks are not compressed away.
    This prompt returns additional candidates only; Python deduplicates.
    """
    existing = "\n".join(f"- {item}" for item in existing_items[:80])
    if not existing:
        existing = "- none"

    system = (
        "You are doing a recall pass for an administrative meeting "
        "protocol. The previous pass may have missed useful local points. "
        "Your job is to scan this time window carefully and extract "
        "additional practical items.\n\n"
        "Return JSON only, with this shape:\n"
        "{\n"
        '  "items": [\n'
        "    {\n"
        '      "type": "decision|task|open_question|risk|thesis",\n'
        '      "text": "practical takeaway in Russian",\n'
        '      "owner": "responsible person/department, or empty",\n'
        '      "deadline": "deadline, or empty",\n'
        '      "speaker": "who proposed/confirmed/raised it, or empty",\n'
        '      "evidence_quote": "5-20 words from this transcript window",\n'
        '      "timestamp": "HH:MM:SS or MM:SS if visible, or empty",\n'
        '      "confidence": "high|medium|low"\n'
        "    }\n"
        "  ]\n"
        "}\n\n"
        "Rules:\n"
        "- Do not summarize the whole window in one item. Extract separate "
        "decisions, tasks, risks, open questions, and useful theses.\n"
        "- Prefer over-inclusion. If useful but uncertain, include it with "
        "confidence=low.\n"
        "- Do not repeat an existing item unless this window contains a "
        "more specific separate point.\n"
        "- If the window truly has no practical content, return an empty "
        "items array.\n"
        "- For tasks, infer owner from the discussed department/person when "
        "the transcript or operator context makes it reasonably clear. Use "
        "confidence=medium or confidence=low for inferred owners.\n"
        "- For tasks without an explicit deadline, infer a practical default "
        "when useful: \"1 неделя\" for urgent items, \"1-2 недели\" for normal "
        "operational items, \"до 1 месяца\" for complex/cross-team items. If "
        "uncertain, leave deadline empty.\n"
        "- User-facing text must be Russian.\n"
    )
    if meeting_context:
        system += (
            "\nOperator context. Treat participant names here as "
            "authoritative if present:\n"
            f"{meeting_context}\n"
        )

    user = (
        f"Window: {window_label or 'chronological window'}\n\n"
        "Existing extracted items, do not duplicate:\n"
        f"{existing}\n\n"
        "Transcript window:\n\n"
        f"{window_transcript}"
    )
    return [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]


